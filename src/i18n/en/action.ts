/** "1 card", "2 cards": the English count the Anki strings below share. */
const cards = (n: number): string => `${n} card${n === 1 ? '' : 's'}`;

/**
 * The toolbar popup (src/action.ts, src/action.html).
 *
 * The small window that opens from the extension's icon in the browser's
 * toolbar: whether the extension is working on this page, menus to choose
 * the video's subtitle tracks, and a line at the foot on Anki. The strings
 * without a value are in the popup's markup too, by their key in data-i18n.
 */
export const action = {
  /** A link at the top, to the help page. */
  help: 'Help',
  /** Button at the top: opens the options page. */
  settings: 'Settings',
  /** That button's tooltip. */
  settingsTip: 'All settings',

  // What the extension is doing on this page
  /** While the popup asks the page. */
  checkingPage: 'Checking this page…',
  /** The page has no part of the extension in it. */
  notActive:
    'Not active on this page. Open a video on YouTube, Netflix, or another supported site. If you just installed or reloaded Libregaku, reload the tab.',
  /** The page is not on a site the extension works on. */
  unsupported: 'Libregaku works on YouTube, Netflix, Disney+, Prime Video, HBO Max, Apple TV and Viki.',
  /** On one of those sites, with no video open. `site` is the site's name. */
  worksOn: (site: string): string => `Libregaku works on ${site}.`,
  /** On a supported site, with no subtitles yet. `site` is the site's name. */
  waitingForSubtitles: (site: string): string => `Waiting for subtitles on ${site}. Make sure they're turned on.`,
  /** Working. `title` is the video's title, from the site. */
  activeOn: (title: string): string => `Active — ${title}`,
  /** Working, on a video with no title to show. */
  active: 'Active on this video.',

  // The subtitle tracks for this video. Track names come from the site and are shown as they are.
  /** The menu of tracks for the subtitles being learned from. */
  subtitlesTrack: 'Subtitles',
  /** The menu of tracks for the translation under them. */
  translationTrack: 'Translation',
  /** Its first choice: no translation. */
  noTranslation: 'None',
  /** A track the site generated by speech recognition. `track` is its name, from the site. */
  generatedTrack: (track: string): string => `${track} (auto)`,

  // Sentence audio on a video that cannot be recorded directly, such as Netflix's
  /** Before the permission is given, which is asked for on the options page. */
  captureNeedsPermission: "Recording sentence audio here needs permission to capture this tab's sound.",
  /** Button: opens the options page, where the permission is asked for. */
  captureAllowInSettings: 'Allow in settings',
  /** Once the permission is given, above the button that starts recording. */
  captureReady: 'Sound from protected sites can be recorded only after you turn it on for this tab.',
  /** Button: starts recording this tab's sound. */
  captureStart: 'Record sentence audio here',
  /** Recording could not start, and nothing said why. */
  captureFailed: "Chrome couldn't record this tab.",

  /** Button: opens or closes the transcript panel beside the video. */
  toggleSidebar: 'Toggle Sidebar',

  // Anki, in one line at the foot
  /** While the popup asks Anki whether it is there. */
  ankiChecking: 'Anki: checking…',
  /** `n` is how many cards the extension has made in Anki. */
  ankiConnected: (n: number): string => `Anki connected · ${cards(n)} from Libregaku`,
  ankiOffline: 'Anki not running — words show as new',
  /** `port` is the number of the port Anki answers on. */
  ankiOccupied: (port: number): string => `Another program is using port ${port}, so Anki cannot be reached`,
  /** Settings is the button at the top of the popup; the options page shows the line to add to Anki. */
  ankiBlocked: 'Anki refused this extension — Settings has the line to add',
  ankiBusy: 'Anki did not answer — it may be busy syncing',
  /** Anki said no, and gave no reason. */
  ankiRefused: 'Anki refused the request',
  /** After " · ", following ankiConnected: cards made while Anki was closed, going in now. */
  cardsToAdd: (n: number): string => `${cards(n)} still to add`,
  /** After " · ", following any line but ankiConnected: cards made while Anki was closed, waiting for it. */
  cardsWaiting: (n: number): string => `${cards(n)} waiting for Anki`,
};
