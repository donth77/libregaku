export function describeFailure(id: string): string {
  const a = ASSUMPTIONS.find((x) => x.id === id);
  if (!a) return id;
  return [
    ``,
    `  BROKEN ASSUMPTION: ${a.id}  (${a.site})`,
    `  claimed:  ${a.claim}`,
    `  breaks:   ${a.breaks}`,
    `  fallback: ${a.fallback ?? 'none — this is load-bearing'}`,
    ``,
  ].join('\n');
}
